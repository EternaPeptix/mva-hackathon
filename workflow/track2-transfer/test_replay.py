#!/usr/bin/env python3
"""Small external-reference and fail-closed checks; no biological validation."""

import copy
import json
import unittest

import replay


class PublicTransferChecks(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.config = json.loads((replay.ROOT / "cases.json").read_text())
        manifest = json.loads((replay.ROOT / "sources.json").read_text())
        cls.sources = replay.read_sources(manifest)

    def test_public_reference_consequence_and_non_transfer(self):
        # run also compares full Ensembl CDS and the RefSeq protein annotation.
        result = replay.run(self.config, self.sources)
        trip13 = next(c for c in result["cases"] if c["gene"] == "TRIP13")
        consequence = trip13["variants"]["c.1060C>T"]
        # Yost/ClinVar reports Arg354Ter; these are its independently stated
        # protein consequence and implied last retained residue, not a fixture
        # generated by this engine.
        self.assertEqual(consequence["protein_hgvs"], "p.(Arg354Ter)")
        self.assertEqual(consequence["protein_length_if_translated"], 353)
        self.assertEqual(trip13["routes"][0]["status"], "not_transferred")
        self.assertTrue(all(not r["clinical_recommendation"] for r in trip13["routes"]))

    def test_coordinate_or_reference_mismatch_is_rejected(self):
        ref = replay.refseq(self.sources["NM_004237.4.gb"])
        with self.assertRaisesRegex(ValueError, "Reference mismatch"):
            replay.apply_variant(ref, "c.1060G>T")

    def test_removing_mechanistic_bridge_removes_nomination(self):
        config = copy.deepcopy(self.config)
        del config["mechanisms"]["bubr1-insufficiency-hypothesis"]["route_evidence"]["nad-bubr1"]["proximal_pathway_to_target_bridge"]
        bub1b = replay.run(config, self.sources)["cases"][0]
        self.assertEqual(bub1b["routes"][0]["status"], "evidence_gap")

    def test_disagreeing_external_cds_is_rejected(self):
        sources = dict(self.sources)
        external = json.loads(sources["ENST00000166345.cds.json"])
        external["seq"] = external["seq"][:100] + "N" + external["seq"][101:]
        sources["ENST00000166345.cds.json"] = json.dumps(external)
        with self.assertRaisesRegex(ValueError, "CDS disagree"):
            replay.run(self.config, sources)


if __name__ == "__main__":
    unittest.main()
