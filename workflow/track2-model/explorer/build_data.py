#!/usr/bin/env python3
"""Package a checked slice of retained results for an entirely offline explorer."""
import hashlib
import json
import math
from pathlib import Path


HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / 'population-results.json'
DEFAULT = {
    'renewal': True, 'aneuploid_division_ratio': 1.8,
    'error_probability': 0.04, 'duration': 20.0,
    'intervention': 'selective_aneuploid_killing',
}
FIXED = {
    'initial_senescence_fraction': 0.25, 'senescence_harm': 1.0,
    'senescent_function': 0.25, 'senescent_niche_weight': 0.0,
    'aneuploid_function': 0.5, 'senolytic_offtarget_fraction': 0.02,
    'capacity': 2000.0,
}


def close(a, b):
    if not math.isclose(a, b, rel_tol=1e-11, abs_tol=1e-9):
        raise ValueError(f'Retained result consistency check failed: {a} != {b}')


def build():
    source_bytes = SOURCE.read_bytes()
    source = json.loads(source_bytes)
    model_hash = hashlib.sha256((HERE.parent / 'population.py').read_bytes()).hexdigest()
    if model_hash != source['source_sha256']:
        raise ValueError('population.py no longer matches the retained result provenance')
    rows = [r for r in source['rows'] if all(r['scenario'][k] == v for k, v in FIXED.items())]
    key = lambda r: (r['scenario']['renewal'], r['scenario']['aneuploid_division_ratio'],
                     r['scenario']['error_probability'], r['duration'], r['intervention'])
    indexed = {key(r): r for r in rows}
    if len(rows) != 192 or len(indexed) != len(rows):
        raise ValueError('Expected a unique 24-scenario × 8-arm retained slice')
    for row in rows:
        baseline = indexed[key(row)[:-1] + ('untreated',)]
        cells = row['final_compartments']
        close(sum(cells.values()), row['live_cells'])
        close(sum(cells[k] for k in ('P_E', 'D_E', 'S_E')) / row['live_cells'], row['euploid_fraction'])
        close(row['raw_output_ratio'], row['raw_differentiated_cell_time'] / baseline['raw_differentiated_cell_time'])
        close(row['weighted_output_ratio'], row['weighted_functional_cell_time'] / baseline['weighted_functional_cell_time'])
        close(row['euploid_fraction_change'], row['euploid_fraction'] - baseline['euploid_fraction'])
    example = indexed[(True, 1.8, 0.04, 20.0, 'selective_aneuploid_killing')]
    baseline = indexed[(True, 1.8, 0.04, 20.0, 'untreated')]
    for arm, row in [('selective_aneuploid_killing', example), ('untreated', baseline)]:
        reference = source['illustrative_trajectories']['renewing']['arms'][arm]
        for field in ('euploid_fraction', 'raw_differentiated_cell_time', 'live_cells', 'weighted_functional_cell_time'):
            close(row[field], reference[field])
    if round(example['euploid_fraction_change'] * 100, 1) != 16.8:
        raise ValueError('Retained example chromosome-normal fraction has changed')
    if round((example['raw_output_ratio'] - 1) * 100, 1) != -11.0:
        raise ValueError('Retained example raw differentiated-cell time has changed')
    payload = {
        'schema_version': 1,
        'title': 'Cell selection and tissue output',
        'method': 'Lookup of retained results; no browser simulation or interpolation.',
        'source_file': '../population-results.json',
        'source_sha256': hashlib.sha256(source_bytes).hexdigest(),
        'model_source_sha256': model_hash,
        'scope': source['scope'], 'time_unit': source['time_unit'],
        'parameter_status': source['parameter_status'],
        'fixed_assumptions': FIXED, 'default': DEFAULT,
        'options': {
            'renewal': [True, False],
            'aneuploid_division_ratio': sorted({r['scenario']['aneuploid_division_ratio'] for r in rows}),
            'error_probability': sorted({r['scenario']['error_probability'] for r in rows}),
            'duration': sorted({r['duration'] for r in rows}),
        },
        'numerical_checks': source['numerical_checks'],
        'rows': rows,
    }
    output = HERE / 'data.js'
    output.write_text('// Generated by build_data.py from retained population-results.json.\n'
                      'window.CELL_SELECTION_DATA = ' + json.dumps(payload, separators=(',', ':'), allow_nan=False) + ';\n')
    print(f'Checked and packaged {len(rows)} retained rows: 24 scenarios × 8 arms.')
    print('Default example verified against retained illustrative results: +16.8 pp; −11.0% raw output.')
    print(f'Wrote {output.name} ({output.stat().st_size:,} bytes).')


if __name__ == '__main__':
    build()
